  var cache = new Map();

  // Pre-render a string to an offscreen canvas (with optional glow baked in).
  function makeCanvas(text, scale, color, glow) {
    var chars = text.toUpperCase().split("");
    var w = chars.length * 6 * scale - scale;
    var h = 7 * scale;
    var pad = glow ? Math.ceil(glow * 1.6) : 0;
    var cv = document.createElement("canvas");
    cv.width = w + pad * 2;
    cv.height = h + pad * 2;
    var c = cv.getContext("2d");
    c.fillStyle = color;
    if (glow) {
      c.shadowColor = color;
      c.shadowBlur = glow;
    }
    var x0 = pad, y0 = pad;
    for (var pass = 0; pass < (glow ? 2 : 1); pass++) {
      for (var i = 0; i < chars.length; i++) {
        var g = GLYPHS[chars[i]] || GLYPHS[" "];
        for (var row = 0; row < 7; row++) {
          for (var col = 0; col < 5; col++) {
            if (g[row][col] === "#") {
              c.fillRect(x0 + (i * 6 + col) * scale, y0 + row * scale, scale, scale);
            }
          }
        }
      }
    }
    return cv;
  }

  function getCanvas(text, scale, color, glow) {
    var key = text + "|" + scale + "|" + color + "|" + (glow || 0);
    var cv = cache.get(key);
    if (!cv) {
      cv = makeCanvas(text, scale, color, glow);
      cache.set(key, cv);
      if (cache.size > 400) { // trim oldest
        var first = cache.keys().next().value;
        cache.delete(first);
      }
    }
    return cv;
  }

  /**
   * Draw pixel text.
   * @param {CanvasRenderingContext2D} ctx
   * @param {string} text
   * @param {number} x
   * @param {number} y
   * @param {number} scale  pixel size
   * @param {string} color
   * @param {object} [opt]  { align: 'left'|'center'|'right', glow: px, alpha }
   */
  function drawText(ctx, text, x, y, scale, color, opt) {
    opt = opt || {};
    var cv = getCanvas(text, scale, color, opt.glow || 0);
    var w = cv.width;
    var px = x;
    if (opt.align === "center") px = x - w / 2;
    else if (opt.align === "right") px = x - w;
    var prevAlpha = ctx.globalAlpha;
    if (opt.alpha != null) ctx.globalAlpha = opt.alpha;
    ctx.drawImage(cv, Math.round(px), Math.round(y));
    ctx.globalAlpha = prevAlpha;
    return w;
  }

  function textWidth(text, scale) {
    return text.length * 6 * scale - scale;
  }

  global.RetroFont = { drawText: drawText, textWidth: textWidth, getCanvas: getCanvas };
